#!/usr/bin/env python3
"""Execute all 8 thesis evidence gates from read-only local copies of Google Drive files.

Inputs: download the Drive originals unmodified to --data-dir. This script does not
know Drive credentials, move Drive files, silently impute, fabricate same-site data,
or generate field-validated synthetic results.
"""
import argparse,os,subprocess,sys,time
from pathlib import Path

def launch(command,cwd):
 print('\nRUN', ' '.join(map(str,command)),flush=True)
 p=subprocess.run([str(x) for x in command],cwd=str(cwd),check=True)
 return p.returncode

def main():
 parser=argparse.ArgumentParser(description='Power–EV transport science evidence gate validation')
 parser.add_argument('--data-dir',default='/mnt/data',help='folder with source files downloaded unchanged from Google Drive')
 parser.add_argument('--root',default=str(Path(__file__).resolve().parent),help='output project directory')
 parser.add_argument('--skip-heavy-vehicle',action='store_true',help='reuse existing vehicle output generated by this pipeline only')
 a=parser.parse_args();data=Path(a.data_dir).resolve();root=Path(a.root).resolve()
 needed=['Barug2025_sensordata.csv','Barug2025_calculated.csv','doi-10.48804-8kpdtw.zip','Measurement_data.xlsx','Session_data.xlsx']
 absent=[x for x in needed if not (data/x).is_file()]
 if absent:raise SystemExit('MISSING ORIGINAL DRIVE FILES '+', '.join(absent)+' — download without modification and rerun')
 for d in ['01_provenance','02_vehicle','03_transformer','04_epfl','05_evse','06_coupling','07_vvuq','08_services']:(root/d).mkdir(parents=True,exist_ok=True)
 py=sys.executable
 launch([py,root/'01_provenance'/'make_registry.py','--data',data,'--out',root/'01_provenance'],root)
 launch([py,root/'other_source_screen.py',data,root],root)
 if not a.skip_heavy_vehicle:
  env=os.environ.copy();env['BEV_SOURCE']=str(data/'doi-10.48804-8kpdtw.zip')
  print('\nRUN vehicle model (with complete session-wise split)',flush=True)
  subprocess.run([py,str(root/'02_vehicle'/'run_vehicle_validation.py')],check=True,cwd=root,env=env)
 elif not (root/'02_vehicle'/'15min_uncertainty_screen.csv').exists():
  raise SystemExit('--skip-heavy-vehicle requested but the prior output is missing')
 launch([py,root/'02_vehicle'/'diagnose_dc.py','--archive',data/'doi-10.48804-8kpdtw.zip','--out',root/'02_vehicle'],root)
 launch([py,root/'03_transformer'/'transformer_calibration.py','--sensor',data/'Barug2025_sensordata.csv','--out',root/'03_transformer'],root)
 launch([py,root/'03_transformer'/'transformer_24h.py','--sensor',data/'Barug2025_sensordata.csv','--fit',root/'03_transformer'/'transformer_candidate_fit.json','--out',root/'03_transformer'],root)
 launch([py,root/'04_epfl'/'audit_epfl.py','--measurement',data/'Measurement_data.xlsx','--session',data/'Session_data.xlsx','--out',root/'04_epfl'],root)
 launch([py,root/'finalize.py',root],root)
 print('\nCOMPLETE. Read EXECUTED_FINDINGS.md and acceptance_gates.csv; no coupled field validation has been claimed.',flush=True)

if __name__=='__main__':main()
